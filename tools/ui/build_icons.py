def hex_rgba(h: str) -> tuple:
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


def draw(palette: dict, grid: list) -> Image.Image:
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(grid[:16]):
        row = (row.replace(" ", "") + "." * 16)[:16]
        for x, ch in enumerate(row):
            if ch == "o":
                im.putpixel((x, y), OUTLINE)
            elif ch in palette:
                im.putpixel((x, y), hex_rgba(palette[ch]))
    return im.resize((32, 32), Image.NEAREST)


if __name__ == "__main__":
    out = Path("assets/sprites/ui")
    made = []
    for name, (pal, grid) in ICONS.items():
        bad = [k for k, r in enumerate(grid) if len(r.replace(" ", "")) != 16]
        if bad or len(grid) != 16:
            print(f"{name}: rows {bad} are not 16 wide (or not 16 rows); padded")
        p = out / f"{name}.png"
        p.parent.mkdir(parents=True, exist_ok=True)
        im = draw(pal, grid)
        im.save(p)
        made.append((name, im))
    sheet = Image.new("RGBA", (len(made) * 80, 110), (36, 43, 37, 255))
    d = ImageDraw.Draw(sheet)
    for k, (name, im) in enumerate(made):
        sheet.alpha_composite(im.resize((64, 64), Image.NEAREST), (k * 80 + 8, 8))
        d.text((k * 80 + 4, 84), name.split("/")[1][:11], fill=(255, 244, 232, 255))
    sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save("docs/ui/icons_sheet.png")
    print(len(made), "icons")
