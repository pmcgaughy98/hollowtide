"""Reproduce all14 world PNGs from local archived images/masks only.
Run in a COPY of this archive. No game, network, renderer or generator is used.
The PNG byte check targets the archived runtime manifest; Godot import metadata
is retained exact but is not generated by this artwork-only builder.
"""
from pathlib import Path
import json,hashlib,subprocess,sys
from PIL import Image
ROOT=Path(__file__).resolve().parent
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
manifest=json.loads((ROOT/'runtime-manifest.json').read_text(encoding='utf-8'))
builders=['phase1/build_room_linework.py','phase1/build_building_linework.py','build_room_material_detail.py','build_world_approaches.py']
runs=[]
for rel in builders:
 result=subprocess.run([sys.executable,str(ROOT/rel)],cwd=ROOT,capture_output=True,text=True,encoding='utf-8')
 runs.append({'builder':rel,'exit_code':result.returncode,'stdout':result.stdout,'stderr':result.stderr})
 if result.returncode!=0:raise RuntimeError(f'Builder failed: {rel}: {result.stderr}')
records=[]
for r in manifest['files']:
 rel=r['project_relative_path']
 if not rel.endswith('.png'):continue
 name=Path(rel).name
 if '/courtyard_home_linework_' in rel: rebuilt=ROOT/'phase1/home-interior-linework-2026-10-04/prepared'/name
 elif '/world_linework_' in rel:rebuilt=ROOT/'phase1/world-buildings-linework-2026-10-04/prepared'/name
 elif '/courtyard_home_detail_' in rel:rebuilt=ROOT/'room-coalcrest-detail-2026-10-05/prepared'/name
 elif '/world_approaches_' in rel:rebuilt=ROOT/'world-detail-audit-2026-10-05/candidate-approaches'/name
 else:raise RuntimeError(rel)
 reference=ROOT/r['archive_relative_path']
 a=Image.open(reference).convert('RGBA');b=Image.open(rebuilt).convert('RGBA')
 row={'project_relative_path':rel,'rebuild_relative_path':rebuilt.relative_to(ROOT).as_posix(),'expected_sha256':r['sha256'],'actual_sha256':sha(rebuilt),'bytes_exact':sha(rebuilt)==r['sha256'],'RGBA_pixels_exact':a.size==b.size and a.tobytes()==b.tobytes(),'native_size':list(b.size)}
 records.append(row)
assert len(records)==14
report={'passed':all(x['bytes_exact'] and x['RGBA_pixels_exact'] for x in records),'reproduced_PNG_count':len(records),'artwork_generation_requests':0,'network_calls':0,'game_launches':0,'PNG_source_resampling':False,'import_metadata':'Exact copied engine sidecars, not rebuilt by this artwork-only helper.','builder_runs':runs,'outputs':records}
(ROOT/'rebuild-results.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
assert report['passed'],'Rebuild mismatch'
print(json.dumps({'passed':True,'reproduced_pngs':14,'all_bytes_exact':True,'all_RGBA_pixels_exact':True},indent=2))
